import type {
  FoodCategory,
  FoodItem,
  FoodPreparation,
  FoodSource,
} from '../db/types';

export const SEED_TIMESTAMP_V1 = '2026-01-01T12:00:00.000Z';

interface CatalogFoodInput {
  id: string;
  name: string;
  category: FoodCategory;
  preparation: FoodPreparation;
  servingLabel: string;
  servingGrams: number;
  unit?: 'g' | 'ml';
  /** Valores nutricionais padronizados por 100g (ou 100ml) da parte comestível. */
  per100: {
    calories: number;
    protein: number;
    carbs: number;
    fat: number;
    fiber?: number | null;
  };
  source: FoodSource;
  sourceId?: string;
  carbBasis?: 'available' | 'total';
  aliases?: string[];
  isRegionalRS?: boolean;
}

function round1(value: number): number {
  return Math.round(value * 10) / 10;
}

function defineCatalogFood(input: CatalogFoodInput): FoodItem {
  const factor = input.servingGrams / 100;
  const fiberValue =
    input.per100.fiber === undefined || input.per100.fiber === null
      ? null
      : round1(input.per100.fiber * factor);

  return {
    id: input.id,
    name: input.name,
    servingLabel: input.servingLabel,
    servingGrams: input.servingGrams,
    unit: input.unit ?? 'g',
    calories: Math.round(input.per100.calories * factor),
    protein: round1(input.per100.protein * factor),
    carbs: round1(input.per100.carbs * factor),
    fat: round1(input.per100.fat * factor),
    fiber: fiberValue,
    category: input.category,
    preparation: input.preparation,
    aliases: input.aliases,
    isRegionalRS: input.isRegionalRS,
    source: input.source,
    sourceId: input.sourceId,
    sourceUpdatedAt: '2026-11-23',
    carbBasis: input.carbBasis ?? (input.source === 'TBCA 7.3' ? 'available' : 'total'),
    createdAt: SEED_TIMESTAMP_V1,
  };
}

